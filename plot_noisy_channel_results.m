function summary = plot_noisy_channel_results(cfg)
%PLOT_NOISY_CHANNEL_RESULTS Aggregate point files and produce comparison plots.

    if ~exist(cfg.paths.results_dir, 'dir')
        error('Results directory does not exist: %s', cfg.paths.results_dir);
    end
    summary = struct([]);

    for n = cfg.n_list
        for channel_idx = 1:numel(cfg.channel_types)
            channel_type = cfg.channel_types{channel_idx};
            points = struct([]);
            for ebno_db = cfg.ebno_db
                filename = noisy_channel_result_file(cfg, n, channel_type, ebno_db);
                if ~isfile(filename)
                    continue;
                end
                loaded = load(filename, 'result');
                if loaded.result.complete
                    points(end+1).result = loaded.result; %#ok<AGROW>
                end
            end
            if isempty(points)
                continue;
            end

            ebno = arrayfun(@(x) x.result.scenario.ebno_db, points);
            [ebno, order] = sort(ebno);
            points = points(order);
            coded = arrayfun(@(x) x.result.metrics.coded.weighted_error, points);
            uncoded = arrayfun(@(x) x.result.metrics.uncoded.weighted_error, points);
            noiseless = arrayfun(@(x) x.result.metrics.noiseless.weighted_error, points);
            coded_empirical = arrayfun( ...
                @(x) x.result.metrics.coded.balanced_error, points);
            uncoded_empirical = arrayfun( ...
                @(x) x.result.metrics.uncoded.balanced_error, points);
            noiseless_empirical = arrayfun( ...
                @(x) x.result.metrics.noiseless.balanced_error, points);
            coded_fpr = arrayfun(@(x) x.result.metrics.coded.fpr, points);
            coded_fnr = arrayfun(@(x) x.result.metrics.coded.fnr, points);
            coded_max = max(coded_fpr, coded_fnr);
            uncoded_fpr = arrayfun(@(x) x.result.metrics.uncoded.fpr, points);
            uncoded_fnr = arrayfun(@(x) x.result.metrics.uncoded.fnr, points);
            uncoded_max = max(uncoded_fpr, uncoded_fnr);
            noiseless_fpr = arrayfun(@(x) x.result.metrics.noiseless.fpr, points);
            noiseless_fnr = arrayfun(@(x) x.result.metrics.noiseless.fnr, points);
            noiseless_max = max(noiseless_fpr, noiseless_fnr);
            ldpc_fer = arrayfun(@(x) x.result.metrics.ldpc_fer, points);
            ldpc_ber = arrayfun(@(x) x.result.metrics.ldpc_payload_ber, points);
            coded_tuple = arrayfun(@(x) x.result.metrics.coded_tuple_error_rate, points);
            tuples = arrayfun(@(x) x.result.tuples, points);
            frames = arrayfun(@(x) x.result.frames, points);
            zero_trials = arrayfun( ...
                @(x) x.result.counts.coded.actual_zero, points);
            one_trials = arrayfun( ...
                @(x) x.result.counts.coded.actual_one, points);
            class_trials = min(zero_trials, one_trials);
            payload_bit_trials = arrayfun( ...
                @(x) x.result.channel_counts.ldpc_payload_bits, points);
            rates = noisy_channel_rate_metadata(points(1).result);

            coded_plot = zero_safe(coded, tuples);
            uncoded_plot = zero_safe(uncoded, tuples);
            noiseless_plot = zero_safe(noiseless, tuples);
            coded_empirical_plot = zero_safe(coded_empirical, tuples);
            uncoded_empirical_plot = zero_safe(uncoded_empirical, tuples);
            noiseless_empirical_plot = zero_safe(noiseless_empirical, tuples);
            fer_plot = zero_safe(ldpc_fer, frames);
            ber_plot = zero_safe(ldpc_ber, payload_bit_trials);
            tuple_plot = zero_safe(coded_tuple, tuples);

            fig = figure('Visible', 'off', 'Color', 'w', ...
                'Position', [100 100 1550 440]);
            layout = tiledlayout(fig, 1, 3, ...
                'TileSpacing', 'compact', 'Padding', 'compact');

            nexttile(layout);
            semilogy(ebno, coded_plot, 'bo-', 'LineWidth', 1.8, 'DisplayName', 'LDPC + BFC');
            hold on;
            semilogy(ebno, uncoded_plot, 'rx-', 'LineWidth', 1.6, 'DisplayName', 'Uncoded BPSK + BFC');
            semilogy(ebno, noiseless_plot, 'k--', 'LineWidth', 1.5, 'DisplayName', 'Noiseless BFC');
            grid on;
            xlabel('E_b/N_0 (dB)');
            ylabel('Prior-weighted BFC error probability');
            title(sprintf('n=%d, %s', n, upper(channel_type)));
            legend('Location', 'best');

            nexttile(layout);
            semilogy(ebno, coded_empirical_plot, 'bo-', ...
                'LineWidth', 1.8, 'DisplayName', 'LDPC + BFC');
            hold on;
            semilogy(ebno, uncoded_empirical_plot, 'rx-', ...
                'LineWidth', 1.6, 'DisplayName', 'Uncoded BPSK + BFC');
            semilogy(ebno, noiseless_empirical_plot, 'k--', ...
                'LineWidth', 1.5, 'DisplayName', 'Noiseless BFC');
            grid on;
            xlabel('E_b/N_0 (dB)');
            ylabel('(FP + FN) / number of trials');
            title('Balanced-sample decision error');
            legend('Location', 'best');

            nexttile(layout);
            semilogy(ebno, fer_plot, 'ms-', 'LineWidth', 1.8, 'DisplayName', 'LDPC FER');
            hold on;
            semilogy(ebno, ber_plot, 'gd-', 'LineWidth', 1.6, 'DisplayName', 'LDPC payload BER');
            semilogy(ebno, tuple_plot, 'c^-', 'LineWidth', 1.6, 'DisplayName', 'Coded tuple error');
            grid on;
            xlabel('E_b/N_0 (dB)');
            ylabel('Error rate');
            title(sprintf(['R_{payload}=%.4f, \\nu=%.3g, ' ...
                'R_{\\Sigma}=%.4f'], rates.ldpc_payload_rate, ...
                rates.channel_uses_per_bfc_decision, ...
                rates.parallel_bfc_rate));
            legend('Location', 'best');

            output_png = fullfile(cfg.paths.results_dir, ...
                sprintf('noisy_channel_n_%d_%s.png', n, lower(channel_type)));
            exportgraphics(fig, output_png, 'Resolution', 160);
            close(fig);

            decision_data = { ...
                coded_empirical, uncoded_empirical, noiseless_empirical, tuples; ...
                coded_fpr, uncoded_fpr, noiseless_fpr, zero_trials; ...
                coded_fnr, uncoded_fnr, noiseless_fnr, one_trials; ...
                coded_max, uncoded_max, noiseless_max, class_trials};
            decision_titles = { ...
                'Balanced average error', 'False-positive rate', ...
                'False-negative rate', 'max(FPR, FNR)'};
            decision_fig = figure('Visible', 'off', 'Color', 'w', ...
                'Position', [100 100 1120 820]);
            decision_layout = tiledlayout(decision_fig, 2, 2, ...
                'TileSpacing', 'compact', 'Padding', 'compact');
            for metric_index = 1:4
                ax = nexttile(decision_layout);
                semilogy(ax, ebno, zero_safe( ...
                    decision_data{metric_index, 1}, ...
                    decision_data{metric_index, 4}), ...
                    'bo-', 'LineWidth', 1.8, 'DisplayName', 'LDPC + BFC');
                hold(ax, 'on');
                semilogy(ax, ebno, zero_safe( ...
                    decision_data{metric_index, 2}, ...
                    decision_data{metric_index, 4}), ...
                    'rx-', 'LineWidth', 1.5, 'DisplayName', 'Uncoded + BFC');
                semilogy(ax, ebno, zero_safe( ...
                    decision_data{metric_index, 3}, ...
                    decision_data{metric_index, 4}), ...
                    'k--', 'LineWidth', 1.4, 'DisplayName', 'Noiseless BFC');
                set(ax, 'YScale', 'log');
                grid(ax, 'on');
                xlabel(ax, 'E_b/N_0 (dB)');
                ylabel(ax, 'Probability');
                title(ax, decision_titles{metric_index});
                legend(ax, 'Location', 'best');
            end
            sgtitle(decision_layout, sprintf('n=%d, %s: conditional BFC errors', ...
                n, upper(channel_type)));
            decision_png = fullfile(cfg.paths.results_dir, sprintf( ...
                'noisy_channel_n_%d_%s_decision_metrics.png', ...
                n, lower(channel_type)));
            exportgraphics(decision_fig, decision_png, 'Resolution', 200);
            close(decision_fig);

            intrinsic_error = arrayfun(@(x) decomposition_value( ...
                x.result, 'intrinsic_error'), points);
            channel_created = arrayfun(@(x) decomposition_value( ...
                x.result, 'channel_created_error'), points);
            channel_corrected = arrayfun(@(x) decomposition_value( ...
                x.result, 'channel_corrected_intrinsic_error'), points);
            decomposition_fig = figure('Visible', 'off', 'Color', 'w', ...
                'Position', [100 100 1120 430]);
            decomposition_layout = tiledlayout(decomposition_fig, 1, 2, ...
                'TileSpacing', 'compact', 'Padding', 'compact');
            channel_ax = nexttile(decomposition_layout);
            semilogy(channel_ax, ebno, fer_plot, 'ms-', 'LineWidth', 1.8, ...
                'DisplayName', 'LDPC FER');
            hold(channel_ax, 'on');
            semilogy(channel_ax, ebno, ber_plot, 'gd-', 'LineWidth', 1.6, ...
                'DisplayName', 'LDPC payload BER');
            semilogy(channel_ax, ebno, tuple_plot, 'c^-', 'LineWidth', 1.6, ...
                'DisplayName', 'Decoded tuple error');
            set(channel_ax, 'YScale', 'log');
            grid(channel_ax, 'on');
            xlabel(channel_ax, 'E_b/N_0 (dB)');
            ylabel(channel_ax, 'Error rate');
            title(channel_ax, 'Channel-code errors');
            legend(channel_ax, 'Location', 'best');

            transition_ax = nexttile(decomposition_layout);
            semilogy(transition_ax, ebno, zero_safe(intrinsic_error, tuples), ...
                'k--', 'LineWidth', 1.6, 'DisplayName', 'Intrinsic BFC error');
            hold(transition_ax, 'on');
            semilogy(transition_ax, ebno, zero_safe(channel_created, tuples), ...
                'ro-', 'LineWidth', 1.6, 'DisplayName', 'Channel-created error');
            semilogy(transition_ax, ebno, zero_safe(channel_corrected, tuples), ...
                'b^-', 'LineWidth', 1.6, ...
                'DisplayName', 'Channel-corrected intrinsic error');
            semilogy(transition_ax, ebno, coded_empirical_plot, ...
                'md-', 'LineWidth', 1.8, 'DisplayName', 'End-to-end error');
            set(transition_ax, 'YScale', 'log');
            grid(transition_ax, 'on');
            xlabel(transition_ax, 'E_b/N_0 (dB)');
            ylabel(transition_ax, 'Fraction of trials');
            title(transition_ax, 'P_{end}=P_{intrinsic}+P_{created}-P_{corrected}');
            legend(transition_ax, 'Location', 'best');
            sgtitle(decomposition_layout, sprintf('n=%d, %s: error decomposition', ...
                n, upper(channel_type)));
            decomposition_png = fullfile(cfg.paths.results_dir, sprintf( ...
                'noisy_channel_n_%d_%s_decomposition.png', ...
                n, lower(channel_type)));
            exportgraphics(decomposition_fig, decomposition_png, 'Resolution', 200);
            close(decomposition_fig);

            entry = struct( ...
                'n', n, ...
                'channel', lower(channel_type), ...
                'ebno_db', ebno, ...
                'coded_error', coded, ...
                'uncoded_error', uncoded, ...
                'noiseless_error', noiseless, ...
                'coded_empirical_decision_error', coded_empirical, ...
                'uncoded_empirical_decision_error', uncoded_empirical, ...
                'noiseless_empirical_decision_error', noiseless_empirical, ...
                'coded_fpr', coded_fpr, ...
                'coded_fnr', coded_fnr, ...
                'coded_max_conditional_error', coded_max, ...
                'uncoded_fpr', uncoded_fpr, ...
                'uncoded_fnr', uncoded_fnr, ...
                'uncoded_max_conditional_error', uncoded_max, ...
                'noiseless_fpr', noiseless_fpr, ...
                'noiseless_fnr', noiseless_fnr, ...
                'noiseless_max_conditional_error', noiseless_max, ...
                'intrinsic_error', intrinsic_error, ...
                'channel_created_error', channel_created, ...
                'channel_corrected_intrinsic_error', channel_corrected, ...
                'ldpc_fer', ldpc_fer, ...
                'ldpc_payload_ber', ldpc_ber, ...
                'coded_tuple_error', coded_tuple, ...
                'tuples', tuples, ...
                'frames', frames, ...
                'actual_zero_trials', zero_trials, ...
                'actual_one_trials', one_trials, ...
                'ldpc_code_rate', rates.ldpc_code_rate, ...
                'ldpc_payload_rate', rates.ldpc_payload_rate, ...
                'noiseless_bfc_rate', rates.noiseless_bfc_rate, ...
                'parallel_bfc_rate', rates.parallel_bfc_rate, ...
                'channel_uses_per_bfc_decision', ...
                    rates.channel_uses_per_bfc_decision);
            if isempty(summary)
                summary = entry;
            else
                summary(end+1) = orderfields(entry, summary); %#ok<AGROW>
            end
        end
    end

    save(fullfile(cfg.paths.results_dir, 'summary_noisy_channel.mat'), 'summary', 'cfg');
    plot_noisy_channel_n_comparison( ...
        summary, cfg, '', 'rule_of_three', 160);
end

function values = zero_safe(values, trials)
    zero_mask = values <= 0;
    values(zero_mask) = min(1, 3 ./ max(1, trials(zero_mask)));
end

function value = decomposition_value(result, field_name)
    if isfield(result, 'metrics') && ...
            isfield(result.metrics, 'decomposition') && ...
            isfield(result.metrics.decomposition, field_name)
        value = result.metrics.decomposition.(field_name);
    else
        value = NaN;
    end
end

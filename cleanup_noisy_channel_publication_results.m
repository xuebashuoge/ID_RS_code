function outputs = cleanup_noisy_channel_publication_results(output_dir)
%CLEANUP_NOISY_CHANNEL_PUBLICATION_RESULTS Build clean paper artifacts.
%
% This function is intentionally non-destructive. It reads only the
% configuration-locked aggregate summaries and writes a new manifest,
% compression table, MAT summary, and publication figures. Historical point
% files remain untouched.

    if nargin < 1 || isempty(output_dir)
        output_dir = fullfile('results', 'noisy_channel_publication', ...
            'existing_clean');
    end
    if ~exist(output_dir, 'dir')
        mkdir(output_dir);
    end
    figure_dir = fullfile(output_dir, 'figures');
    if ~exist(figure_dir, 'dir')
        mkdir(figure_dir);
    end

    representatives = struct( ...
        'func_type', {'id', 'exact-threshold', 'rank'}, ...
        'label', {'Identification', 'Exact threshold', 'Rank'}, ...
        'n', {40, 42, 40});
    [manifest, aggregate] = build_manifest(representatives);
    outputs.manifest_csv = fullfile(output_dir, ...
        'existing_results_manifest.csv');
    writetable(manifest, outputs.manifest_csv);

    compression = build_compression_table(aggregate, representatives);
    outputs.compression_csv = fullfile(output_dir, ...
        'compression_gain_table.csv');
    writetable(compression, outputs.compression_csv);
    outputs.summary_mat = fullfile(output_dir, ...
        'existing_publication_summary.mat');
    save(outputs.summary_mat, 'aggregate', 'manifest', ...
        'compression', 'representatives');

    outputs.waterfall = plot_existing_waterfall( ...
        representatives, figure_dir);
    outputs.decomposition = plot_existing_decomposition( ...
        representatives, figure_dir);
    outputs.resource_uses = plot_existing_resource_tradeoff( ...
        aggregate, representatives, figure_dir, ...
        'channel_uses_per_bfc_decision');
    outputs.parallel_rate = plot_existing_resource_tradeoff( ...
        aggregate, representatives, figure_dir, 'parallel_bfc_rate');

    fprintf('Clean publication artifacts written below %s\n', output_dir);
end

function [manifest, aggregate] = build_manifest(representatives)
    rows = struct([]);
    aggregate = struct([]);
    for rep_index = 1:numel(representatives)
        func_type = representatives(rep_index).func_type;
        for sweep_type = {'e2', 'ldpc_rate'}
            sweep_name = sweep_type{1};
            summary_file = fullfile('results', ...
                'noisy_channel_tradeoffs', 'server_full', func_type, ...
                sweep_name, 'summary_noisy_channel_tradeoff.mat');
            if ~isfile(summary_file)
                error('Required configuration-locked summary is missing: %s', ...
                    summary_file);
            end
            saved = load(summary_file, 'aggregate', 'configs');
            points = saved.aggregate;
            for point_index = 1:numel(points)
                point = points(point_index);
                cfg = matching_config(saved.configs, point.sweep_value);
                source_point = noisy_channel_result_file(cfg, point.n, ...
                    point.channel, point.ebno_db);
                fp_count = round(point.coded_fpr*point.actual_zero_trials);
                fn_count = round(point.coded_fnr*point.actual_one_trials);
                row = struct( ...
                    'function_type', string(func_type), ...
                    'sweep_type', string(sweep_name), ...
                    'source_summary', string(summary_file), ...
                    'source_point', string(source_point), ...
                    'n', point.n, 'K', point.K, 'm', point.m, ...
                    'E2', point.E2, ...
                    'ldpc_code_rate', point.ldpc_code_rate, ...
                    'ebno_db', point.ebno_db, ...
                    'false_positive_count', fp_count, ...
                    'negative_trials', point.actual_zero_trials, ...
                    'false_negative_count', fn_count, ...
                    'positive_trials', point.actual_one_trials, ...
                    'fpr', point.coded_fpr, ...
                    'fnr', point.coded_fnr, ...
                    'max_fpr_fnr', max(point.coded_fpr, point.coded_fnr), ...
                    'fp_plus_fn_over_trials', ...
                        (fp_count+fn_count)/(point.actual_zero_trials+ ...
                        point.actual_one_trials), ...
                    'channel_uses_per_bfc_decision', ...
                        point.channel_uses_per_bfc_decision, ...
                    'parallel_bfc_rate', point.parallel_bfc_rate, ...
                    'frames', point.frames, 'tuples', point.tuples, ...
                    'inference_status', string( ...
                        'pilot; adaptive/event-or-cap stopping'));
                if isempty(rows)
                    rows = row;
                else
                    rows(end+1) = orderfields(row, rows); %#ok<AGROW>
                end
            end
            if isempty(aggregate)
                aggregate = points;
                for idx = 1:numel(aggregate)
                    aggregate(idx).function_type = func_type;
                end
            else
                for idx = 1:numel(points)
                    points(idx).function_type = func_type;
                end
                aggregate = [aggregate, orderfields(points, aggregate)]; %#ok<AGROW>
            end
        end
    end
    manifest = struct2table(rows);
    manifest = sortrows(manifest, ...
        {'function_type', 'sweep_type', 'n', 'ldpc_code_rate', ...
        'E2', 'ebno_db'});
end

function cfg = matching_config(configs, sweep_value)
    cfg = [];
    for index = 1:numel(configs)
        candidate = configs{index};
        if abs(candidate.experiment.value-sweep_value) <= ...
                1e-10*max(1, abs(sweep_value))
            cfg = candidate;
            return;
        end
    end
    error('No saved configuration matches sweep value %.12g.', sweep_value);
end

function table_out = build_compression_table(aggregate, representatives)
    rows = struct([]);
    for rep_index = 1:numel(representatives)
        rep = representatives(rep_index);
        selected = aggregate(strcmp({aggregate.function_type}, rep.func_type) & ...
            strcmp({aggregate.sweep_type}, 'ldpc_rate') & ...
            [aggregate.n] == rep.n & ...
            abs([aggregate.ldpc_code_rate]-0.5) < 1e-12 & ...
            [aggregate.ebno_db] == 0);
        if numel(selected) ~= 1
            error('Compression-table point is missing or duplicated for %s.', ...
                rep.func_type);
        end
        point = selected(1);
        ideal_tagging_uses = point.n/point.ldpc_code_rate;
        baseline_uses = point.m/point.ldpc_code_rate;
        row = struct( ...
            'function_type', string(rep.func_type), ...
            'function_label', string(rep.label), ...
            'n_tag', point.n, 'K', point.K, 'm', point.m, ...
            'ldpc_code_rate', point.ldpc_code_rate, ...
            'ideal_tagging_channel_uses', ideal_tagging_uses, ...
            'actual_tagging_channel_uses', ...
                point.channel_uses_per_bfc_decision, ...
            'transmit_then_compute_channel_uses', baseline_uses, ...
            'ideal_compression_gain', point.m/point.n, ...
            'actual_compression_gain', baseline_uses/ ...
                point.channel_uses_per_bfc_decision);
        if isempty(rows)
            rows = row;
        else
            rows(end+1) = orderfields(row, rows); %#ok<AGROW>
        end
    end
    table_out = struct2table(rows);
end

function files = plot_existing_waterfall(representatives, figure_dir)
    fig = figure('Visible', 'off', 'Color', 'w', ...
        'Position', [100 100 1450 440]);
    layout = tiledlayout(fig, 1, numel(representatives), ...
        'TileSpacing', 'compact', 'Padding', 'compact');
    for rep_index = 1:numel(representatives)
        rep = representatives(rep_index);
        entry = load_representative_summary(rep);
        keep = entry.ebno_db <= 3;
        ebno = entry.ebno_db(keep);
        class_trials = min(entry.actual_zero_trials(keep), ...
            entry.actual_one_trials(keep));
        ax = nexttile(layout);
        hold(ax, 'on');
        plot_upper_bound_series(ax, ebno, ...
            entry.coded_max_conditional_error(keep), class_trials, ...
            'o-', [0 0.35 0.75], 'LDPC + BFC');
        plot_upper_bound_series(ax, ebno, ...
            entry.uncoded_max_conditional_error(keep), class_trials, ...
            'x-', [0.85 0.2 0.15], 'Uncoded BPSK + BFC');
        plot_upper_bound_series(ax, ebno, ...
            entry.noiseless_max_conditional_error(keep), class_trials, ...
            '--', [0.1 0.1 0.1], 'Noiseless BFC');
        style_probability_axis(ax, 'E_b/N_0 (dB)', ...
            'max(FPR, FNR)');
        title(ax, sprintf('%s, n=%d', rep.label, rep.n));
        legend(ax, 'Location', 'southwest');
    end
    title(layout, ['Coded BFC waterfall on AWGN (E_2=0.1, ' ...
        'R_c=1/2; triangles denote zero-event upper bounds)']);
    files = export_figure_pair(fig, fullfile(figure_dir, ...
        'figure_waterfall_max_fpr_fnr'));
    close(fig);
end

function files = plot_existing_decomposition(representatives, figure_dir)
    fig = figure('Visible', 'off', 'Color', 'w', ...
        'Position', [100 100 1450 500]);
    layout = tiledlayout(fig, 1, numel(representatives), ...
        'TileSpacing', 'compact', 'Padding', 'loose');
    for rep_index = 1:numel(representatives)
        rep = representatives(rep_index);
        entry = load_representative_summary(rep);
        keep = entry.ebno_db <= 3;
        ebno = entry.ebno_db(keep);
        trials = entry.tuples(keep);
        ax = nexttile(layout);
        hold(ax, 'on');
        plot_upper_bound_series(ax, ebno, entry.intrinsic_error(keep), ...
            trials, '--', [0.1 0.1 0.1], 'Intrinsic');
        plot_upper_bound_series(ax, ebno, ...
            entry.channel_created_error(keep), trials, ...
            'o-', [0.85 0.2 0.15], 'Channel-created');
        plot_upper_bound_series(ax, ebno, ...
            entry.channel_corrected_intrinsic_error(keep), trials, ...
            '^-', [0.2 0.4 0.8], 'Channel-corrected');
        plot_upper_bound_series(ax, ebno, ...
            entry.coded_empirical_decision_error(keep), trials, ...
            'd-', [0.65 0.15 0.65], 'End-to-end');
        style_probability_axis(ax, 'E_b/N_0 (dB)', ...
            'Balanced diagnostic probability');
        title(ax, sprintf('%s, n=%d', rep.label, rep.n));
        legend(ax, 'Location', 'southwest');
    end
    title(layout, ['Balanced-error diagnostic decomposition: intrinsic + ' ...
        'channel-created - channel-corrected'], 'FontSize', 12);
    files = export_figure_pair(fig, fullfile(figure_dir, ...
        'figure_error_decomposition'));
    close(fig);
end

function files = plot_existing_resource_tradeoff( ...
        aggregate, representatives, figure_dir, resource_name)
    snr_values = [1.5 2.0];
    colors = lines(numel(snr_values));
    fig = figure('Visible', 'off', 'Color', 'w', ...
        'Position', [100 100 1450 440]);
    layout = tiledlayout(fig, 1, numel(representatives), ...
        'TileSpacing', 'compact', 'Padding', 'compact');
    for rep_index = 1:numel(representatives)
        rep = representatives(rep_index);
        ax = nexttile(layout);
        hold(ax, 'on');
        for snr_index = 1:numel(snr_values)
            snr = snr_values(snr_index);
            selected = aggregate(strcmp({aggregate.function_type}, ...
                rep.func_type) & strcmp({aggregate.sweep_type}, 'ldpc_rate') & ...
                [aggregate.n] == rep.n & ...
                abs([aggregate.ebno_db]-snr) < 1e-12);
            [x, order] = sort([selected.(resource_name)]);
            selected = selected(order);
            y = [selected.coded_max_conditional_error];
            semilogy(ax, x, y, 'o-', 'LineWidth', 1.6, ...
                'Color', colors(snr_index, :), ...
                'DisplayName', sprintf('E_b/N_0=%.1f dB', snr));
            if snr_index == 1
            for point_index = 1:numel(selected)
                horizontal_alignment = 'left';
                label = sprintf(' R_c=%.3g', ...
                    selected(point_index).ldpc_code_rate);
                if point_index == numel(selected)
                    horizontal_alignment = 'right';
                    label = sprintf('R_c=%.3g ', ...
                        selected(point_index).ldpc_code_rate);
                end
                vertical_alignment = 'middle';
                if y(point_index) > 0.5
                    vertical_alignment = 'top';
                end
                label_y = y(point_index) * 10^(0.08 * ...
                    (point_index-(numel(selected)+1)/2));
                text(ax, x(point_index), label_y, label, ...
                    'FontSize', 7, 'Color', colors(snr_index, :), ...
                    'HorizontalAlignment', horizontal_alignment, ...
                    'VerticalAlignment', vertical_alignment);
            end
            end
        end
        style_probability_axis(ax, resource_label(resource_name), ...
            'max(FPR, FNR)');
        title(ax, sprintf('%s, n=%d', rep.label, rep.n));
        legend(ax, 'Location', 'best');
    end
    title(layout, ['LDPC-rate resource-reliability tradeoff; ' ...
        'rate labels identify every operating point']);
    files = export_figure_pair(fig, fullfile(figure_dir, ...
        ['figure_pareto_' resource_name]));
    close(fig);
end

function entry = load_representative_summary(rep)
    summary_file = fullfile('results', 'noisy_channel_tradeoffs', ...
        'server_full', rep.func_type, 'ldpc_rate', ...
        'E2_0p1_Rc_0p5', 'summary_noisy_channel.mat');
    saved = load(summary_file, 'summary');
    selected = saved.summary([saved.summary.n] == rep.n & ...
        strcmpi({saved.summary.channel}, 'awgn'));
    if numel(selected) ~= 1
        error('Representative summary is missing or duplicated: %s, n=%d.', ...
            rep.func_type, rep.n);
    end
    entry = selected;
end

function plot_upper_bound_series(ax, x, y, trials, line_style, color, label)
    y = double(y(:).');
    trials = double(trials(:).');
    x = double(x(:).');
    zero_mask = y <= 0;
    line_values = y;
    line_values(zero_mask) = NaN;
    semilogy(ax, x, line_values, line_style, 'LineWidth', 1.7, ...
        'Color', color, 'DisplayName', label);
    if any(zero_mask)
        upper = 3 ./ max(1, trials(zero_mask));
        semilogy(ax, x(zero_mask), upper, 'v', 'LineStyle', 'none', ...
            'MarkerSize', 6, 'Color', color, 'HandleVisibility', 'off');
    end
end

function style_probability_axis(ax, x_label, y_label)
    set(ax, 'YScale', 'log', 'FontSize', 9);
    grid(ax, 'on');
    box(ax, 'on');
    xlabel(ax, x_label);
    ylabel(ax, y_label);
end

function label = resource_label(resource_name)
    switch resource_name
        case 'channel_uses_per_bfc_decision'
            label = 'Physical channel uses per BFC decision, \nu';
        case 'parallel_bfc_rate'
            label = 'Parallel BFC rate, R_{\Sigma} per channel use';
        otherwise
            label = strrep(resource_name, '_', ' ');
    end
end

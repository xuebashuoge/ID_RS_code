function outputs = compile_noisy_channel_publication_results(output_dir)
%COMPILE_NOISY_CHANNEL_PUBLICATION_RESULTS Build fixed-sample paper artifacts.
%
% Reads the completed BP confirmatory waterfall and rate-pareto point files.
% Historical adaptive sweeps and the 200-frame LDPC calibration are excluded
% from inferential tables; they remain useful pilot/sanity-check artifacts.

    root_dir = fileparts(mfilename('fullpath'));
    addpath(root_dir);
    cd(root_dir);
    if nargin < 1 || isempty(output_dir)
        output_dir = fullfile('results', 'noisy_channel_publication', ...
            'confirmatory_bp');
    end
    if ~isfolder(output_dir)
        mkdir(output_dir);
    end
    figure_dir = fullfile(output_dir, 'figures');
    if ~isfolder(figure_dir)
        mkdir(figure_dir);
    end

    waterfall_outputs = plot_noisy_channel_confirmatory_results('waterfall');
    pareto_outputs = plot_noisy_channel_confirmatory_results('rate_pareto');
    waterfall = readtable(waterfall_outputs.csv, 'TextType', 'string');
    pareto = readtable(pareto_outputs.csv, 'TextType', 'string');
    waterfall = addvars(waterfall, repmat("waterfall", height(waterfall), 1), ...
        'Before', 1, 'NewVariableNames', 'experiment');
    pareto = addvars(pareto, repmat("rate_pareto", height(pareto), 1), ...
        'Before', 1, 'NewVariableNames', 'experiment');
    manifest = [waterfall; pareto];
    manifest = sortrows(manifest, {'experiment', 'function_type', ...
        'ldpc_code_rate', 'ebno_db'});

    outputs.manifest_csv = fullfile(output_dir, ...
        'confirmatory_results_manifest.csv');
    writetable(manifest, outputs.manifest_csv);
    diagnostics = build_diagnostic_table(manifest);
    outputs.diagnostics_csv = fullfile(output_dir, ...
        'finite_error_diagnostics.csv');
    writetable(diagnostics, outputs.diagnostics_csv);
    operating_points = select_operating_points(waterfall, 1.5);
    outputs.operating_points_csv = fullfile(output_dir, ...
        'representative_operating_points_1p5dB.csv');
    writetable(operating_points, outputs.operating_points_csv);
    compression = build_compression_table(operating_points);
    outputs.compression_csv = fullfile(output_dir, ...
        'compression_and_rate_table.csv');
    writetable(compression, outputs.compression_csv);
    outputs.decomposition_figure = plot_decomposition(waterfall, figure_dir);
    outputs.summary_mat = fullfile(output_dir, ...
        'confirmatory_publication_summary.mat');
    save(outputs.summary_mat, 'manifest', 'diagnostics', ...
        'operating_points', 'compression');

    fprintf(['Publication artifacts use %d fixed-sample BP points and are ' ...
        'written below %s.\n'], height(manifest), output_dir);
end

function diagnostics = build_diagnostic_table(manifest)
    keys = unique(manifest(:, {'experiment', 'function_type'}), 'rows');
    rows = cell(height(keys), 13);
    tolerance = 100*eps;
    for index = 1:height(keys)
        selected = manifest(manifest.experiment == keys.experiment(index) & ...
            manifest.function_type == keys.function_type(index), :);
        rows(index, :) = {keys.experiment(index), ...
            keys.function_type(index), height(selected), ...
            min(selected.frames), max(selected.frames), ...
            unique_scalar(selected.ldpc_block_length, 'N_b'), ...
            max(selected.empirical_fpr_union_excess), ...
            max(selected.worst_case_fpr_union_excess), ...
            max(selected.fnr_fer_excess), ...
            all(selected.empirical_fpr_union_excess <= tolerance), ...
            all(selected.worst_case_fpr_union_excess <= tolerance), ...
            all(selected.fnr_fer_excess <= tolerance), ...
            "diagnostic_with_empirical_average_FER_not_a_proof_of_maximal_FER"};
    end
    diagnostics = cell2table(rows, 'VariableNames', { ...
        'experiment', 'function_type', 'point_count', 'min_frames', ...
        'max_frames', 'ldpc_block_length', ...
        'max_empirical_fpr_union_excess', ...
        'max_worst_case_fpr_union_excess', 'max_fnr_fer_excess', ...
        'all_empirical_fpr_union_checks_pass', ...
        'all_worst_case_fpr_union_checks_pass', ...
        'all_fnr_fer_checks_pass', 'interpretation'});
end

function value = unique_scalar(values, label)
    values = unique(values);
    if numel(values) ~= 1
        error('%s is not constant within a diagnostic group.', label);
    end
    value = values(1);
end

function selected = select_operating_points(waterfall, ebno_db)
    keep = abs(waterfall.ebno_db-ebno_db) < 1e-12 & ...
        abs(waterfall.ldpc_code_rate-0.5) < 1e-12 & ...
        waterfall.ldpc_block_length == 64800;
    selected = waterfall(keep, :);
    if height(selected) ~= 3
        error('Expected one 1.5-dB, R_c=1/2 point for each function.');
    end
    selected = sortrows(selected, 'function_type');
end

function compression = build_compression_table(points)
    baseline_uses = points.m ./ points.ldpc_code_rate;
    compression = table(points.function_type, points.n, points.K, points.m, ...
        points.S, points.ldpc_block_length, points.ldpc_code_rate, ...
        points.ldpc_payload_rate, points.tuples_per_frame, ...
        points.padding_efficiency, points.channel_uses_per_bfc_decision, ...
        baseline_uses, baseline_uses./points.channel_uses_per_bfc_decision, ...
        points.parallel_bfc_rate, points.tag_error_exponent, ...
        points.effective_error_exponent, ...
        points.asymptotic_parallel_rate_target, points.coded_fpr, ...
        points.coded_fnr, points.ldpc_fer, ...
        'VariableNames', {'function_type', 'tag_length', 'K', 'm', 'S', ...
        'ldpc_block_length', 'ldpc_code_rate', 'ldpc_payload_rate', ...
        'tuples_per_frame', 'padding_efficiency', ...
        'packed_channel_uses_per_decision', ...
        'transmit_then_compute_channel_uses', 'compression_gain', ...
        'finite_parallel_computation_rate', 'tag_error_exponent', ...
        'effective_error_exponent', 'asymptotic_parallel_rate_target', ...
        'coded_fpr_at_1p5dB', 'coded_fnr_at_1p5dB', ...
        'ldpc_fer_at_1p5dB'});
end

function files = plot_decomposition(waterfall, figure_dir)
    function_types = {'id', 'exact-threshold', 'rank'};
    fig = figure('Visible', 'off', 'Color', 'w', ...
        'Position', [100 100 1450 440]);
    layout = tiledlayout(fig, 1, 3, ...
        'TileSpacing', 'compact', 'Padding', 'compact');
    for index = 1:numel(function_types)
        selected = waterfall(strcmp(waterfall.function_type, ...
            function_types{index}), :);
        selected = sortrows(selected, 'ebno_db');
        ax = nexttile(layout);
        hold(ax, 'on');
        plot_probability(ax, selected.ebno_db, selected.coded_fpr, ...
            selected.coded_fpr_zero_event_cluster_upper95, 'o-', ...
            [0 0.35 0.75], 'End-to-end FPR');
        plot_probability(ax, selected.ebno_db, selected.coded_fnr, ...
            selected.coded_fnr_zero_event_cluster_upper95, 's-', ...
            [0.65 0.15 0.65], 'End-to-end FNR');
        plot_probability(ax, selected.ebno_db, selected.noiseless_fpr, ...
            selected.noiseless_fpr_zero_event_cluster_upper95, '--', ...
            [0.1 0.55 0.2], 'Sampled RS collision FPR');
        fer_upper = nan(height(selected), 1);
        zero_fer = selected.ldpc_frame_errors == 0;
        fer_upper(zero_fer) = 1-0.05.^(1./selected.frames(zero_fer));
        plot_probability(ax, selected.ebno_db, selected.ldpc_fer, ...
            fer_upper, '^-', [0.85 0.2 0.15], 'LDPC FER');
        semilogy(ax, selected.ebno_db, selected.rs_worst_case_fpr_bound, ...
            ':', 'LineWidth', 1.6, 'Color', [0.15 0.15 0.15], ...
            'DisplayName', 'RS worst-case bound');
        grid(ax, 'on');
        box(ax, 'on');
        xlabel(ax, 'Payload-referenced E_b/N_0 (dB)');
        ylabel(ax, 'Probability');
        title(ax, sprintf('%s, n_t=%d', ...
            selected.function_label(1), selected.n(1)));
        legend(ax, 'Location', 'best', 'FontSize', 7);
    end
    title(layout, ['Finite-error components, BP DVB-S2 LDPC ' ...
        '(N_b=64800, R_c=1/2, E_{2,t}=0.1, E_{2,eff}=0.05)']);
    base_path = fullfile(figure_dir, 'figure_finite_error_components');
    files = export_figure_pair(fig, base_path);
    close(fig);
end

function plot_probability(ax, x, y, zero_upper, style, color, label)
    positive = isfinite(y) & y > 0;
    semilogy(ax, x(positive), y(positive), style, 'LineWidth', 1.5, ...
        'Color', color, 'DisplayName', label);
    zero = ~positive & isfinite(zero_upper) & zero_upper > 0;
    if any(zero)
        semilogy(ax, x(zero), zero_upper(zero), 'v', ...
            'LineStyle', 'none', 'Color', color, ...
            'HandleVisibility', 'off');
    end
end
